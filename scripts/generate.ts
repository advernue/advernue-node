// Regenerates src/generated/* from spec/openapi.json.  Run: pnpm generate  (node >= 22.18, no deps)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

type Json = any;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec: Json = JSON.parse(readFileSync(join(root, "spec/openapi.json"), "utf8"));
const components: Record<string, Json> = spec.components?.schemas ?? {};
const HEADER = "// GENERATED by scripts/generate.ts from spec/openapi.json. Do not edit.\n";

// ---------- minimal JSON Schema -> TypeScript ----------
const ident = /^[A-Za-z_$][\w$]*$/;
const key = (k: string) => (ident.test(k) ? k : JSON.stringify(k));
const refName = (r: string) => r.split("/").pop()!;

function emit(s: Json, ind = ""): string {
  if (s === true || s == null || (typeof s === "object" && Object.keys(s).length === 0)) return "unknown";
  if (s === false) return "never";
  if (s.$ref) return refName(s.$ref) in components ? refName(s.$ref) : "unknown";
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v: unknown) => JSON.stringify(v)).join(" | ");
  for (const k of ["anyOf", "oneOf"]) if (s[k]) return s[k].map((x: Json) => emit(x, ind)).join(" | ");
  if (s.allOf) return s.allOf.map((x: Json) => `(${emit(x, ind)})`).join(" & ");
  if (Array.isArray(s.type)) return s.type.map((t: string) => emit({ ...s, type: t }, ind)).join(" | ");
  switch (s.type ?? (s.properties ? "object" : undefined)) {
    case "string": return "string";
    case "number": case "integer": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": return `Array<${emit(s.items, ind)}>`;
    case "object": return emitObject(s, ind);
    default: return "unknown";
  }
}

function emitObject(s: Json, ind: string): string {
  const props = s.properties ?? {};
  const req = new Set<string>(s.required ?? []);
  const names = Object.keys(props);
  const ap = s.additionalProperties;
  const open = ap !== undefined && ap !== false;
  const apType = ap && typeof ap === "object" && Object.keys(ap).length ? emit(ap, ind) : "unknown";
  if (!names.length) return open ? `Record<string, ${apType}>` : "Record<string, never>";
  const inner = ind + "  ";
  const lines = names.map((n) => {
    const d = props[n]?.description;
    const doc = d ? `${inner}/** ${String(d).replace(/\*\//g, "*\\/").replace(/\s+/g, " ")} */\n` : "";
    return `${doc}${inner}${key(n)}${req.has(n) ? "" : "?"}: ${emit(props[n], inner)};`;
  });
  if (open) lines.push(`${inner}[key: string]: unknown;`);
  return `{\n${lines.join("\n")}\n${ind}}`;
}

// ---------- JSON Schema for the runtime manifest (CLI / MCP read this) ----------
function rewrite(s: Json): Json {
  if (Array.isArray(s)) return s.map(rewrite);
  if (s && typeof s === "object") {
    const out: Json = {};
    for (const [k, v] of Object.entries(s)) out[k] = k === "$ref" && typeof v === "string" ? `#/$defs/${refName(v)}` : rewrite(v);
    return out;
  }
  return s;
}

// ---------- operations ----------
const pascal = (x: string) => x[0].toUpperCase() + x.slice(1);
const METHODS = ["get", "post", "put", "patch", "delete"];

interface Op { meta: Json; typeBase: string; params: Json[]; bodyTs?: string; respTs: string; hasParams: boolean }
const ops: Op[] = [];
const seen = new Set<string>();

for (const [path, item] of Object.entries<Json>(spec.paths)) {
  for (const m of METHODS) {
    const o = item[m];
    if (!o) continue;
    const id: string = o.operationId;
    const [tag, name, ...rest] = id.split(".");
    if (!tag || !name || rest.length || seen.has(id)) throw new Error(`bad or duplicate operationId ${id}`);
    seen.add(id);

    const all: Json[] = [...(item.parameters ?? []), ...(o.parameters ?? [])];
    const pick = (where: string) => all.filter((p) => p.in === where && p.name !== "dry_run").map((p) => ({
      name: p.name, required: p.in === "path" || !!p.required, schema: rewrite(p.schema ?? {}),
      ...(p.description ? { description: p.description } : {}),
    }));
    const pathParams = pick("path"), query = pick("query");
    const clash = pathParams.find((p) => query.some((q) => q.name === p.name));
    if (clash) throw new Error(`${id}: path/query name clash ${clash.name}`);

    const reqBody = o.requestBody?.content?.["application/json"]?.schema;
    const successCode = Object.keys(o.responses).filter((c) => /^2/.test(c)).sort()[0];
    const success = o.responses[successCode] ?? {};
    const ctype = Object.keys(success.content ?? {})[0];
    const response = !ctype ? "none" : ctype.includes("json") ? "json" : ctype.startsWith("text/") || ctype.includes("javascript") ? "text" : "binary";
    const meta = {
      id, tag, name, method: m.toUpperCase(), path,
      ...(o.summary ? { summary: o.summary } : {}),
      ...(o.deprecated ? { deprecated: true } : {}),
      pathParams, query,
      ...(reqBody ? { body: { required: !!o.requestBody.required, schema: rewrite(reqBody) } } : {}),
      idempotent: all.some((p) => p.in === "header" && p.name.toLowerCase() === "idempotency-key"),
      dryRun: all.some((p) => p.in === "query" && p.name === "dry_run"),
      auth: o.security === undefined || o.security.length > 0,
      response,
    };
    const typeBase = pascal(tag) + pascal(name);
    const respTs = response === "json" ? emit(success.content["application/json"].schema, "") : response === "text" ? "string" : response === "binary" ? "ArrayBuffer" : "void";
    ops.push({ meta, typeBase, params: [...pathParams, ...query], bodyTs: reqBody ? emit(reqBody, "") : undefined, respTs, hasParams: pathParams.length + query.length > 0 });
  }
}

// ---------- write files ----------
const out = join(root, "src/generated");
mkdirSync(out, { recursive: true });

let types = HEADER + "\n";
for (const [n, s] of Object.entries(components)) {
  const d = s.description ? `/** ${String(s.description).replace(/\*\//g, "*\\/")} */\n` : "";
  types += `${d}export type ${n} = ${emit(s)};\n\n`;
}
for (const op of ops) {
  const fields = op.params.map((p) => `  ${key(p.name)}${p.required ? "" : "?"}: ${emit(p.schema, "  ")};`);
  if (op.hasParams) types += `export type ${op.typeBase}Params = {\n${fields.join("\n")}\n};\n`;
  if (op.bodyTs) types += `export type ${op.typeBase}Body = ${op.bodyTs};\n`;
  types += `export type ${op.typeBase}Response = ${op.respTs};\n\n`;
}
writeFileSync(join(out, "types.ts"), types);

const metas = Object.fromEntries(ops.map((o) => [o.meta.id, o.meta]));
writeFileSync(join(out, "operations.ts"), `${HEADER}import type { OperationMeta } from "../meta.js";

export const operations: Record<string, OperationMeta> = ${JSON.stringify(metas, null, 1)};

/** Component schemas as JSON Schema; operation schemas reference these as \`#/$defs/<Name>\`. */
export const componentSchemas: Record<string, Record<string, unknown>> = ${JSON.stringify(rewrite(components), null, 1)};
`);

const imports = ops.flatMap((o) => [o.hasParams && `${o.typeBase}Params`, o.bodyTs && `${o.typeBase}Body`, `${o.typeBase}Response`]).filter(Boolean);
let client = `${HEADER}import type { Call, RequestOptions, WriteOptions, DryRunOptions } from "../runtime.js";
import { operations } from "./operations.js";
import type {\n${imports.map((i) => `  ${i},`).join("\n")}\n} from "./types.js";

export function buildNamespaces(call: Call) {
  const op = (id: string) => operations[id]!;
  return {\n`;
const byTag = new Map<string, Op[]>();
for (const o of ops) byTag.set(o.meta.tag, [...(byTag.get(o.meta.tag) ?? []), o]);
for (const [tag, list] of byTag) {
  client += `    ${key(tag)}: {\n`;
  for (const o of list) {
    const m = o.meta;
    const optT = m.method === "GET" ? "RequestOptions" : m.dryRun ? "DryRunOptions" : m.idempotent ? "WriteOptions" : "RequestOptions";
    const args: string[] = [], pass: string[] = [];
    const anyReq = o.params.some((p) => p.required);
    if (o.hasParams) { args.push(anyReq ? `params: ${o.typeBase}Params` : o.bodyTs && m.body.required ? `params: ${o.typeBase}Params | undefined` : `params?: ${o.typeBase}Params`); pass.push("params"); } else pass.push("undefined");
    if (o.bodyTs) { args.push(`body${m.body.required ? "" : "?"}: ${o.typeBase}Body`); pass.push("body"); } else pass.push("undefined");
    args.push(`opts?: ${optT}`); pass.push("opts");
    const doc = m.summary ? `      /** ${m.method} ${m.path}: ${m.summary.replace(/\*\//g, "")} */\n` : "";
    client += `${doc}      ${key(m.name)}: (${args.join(", ")}): Promise<${o.typeBase}Response> =>\n        call(op(${JSON.stringify(m.id)}), ${pass.join(", ")}) as Promise<${o.typeBase}Response>,\n`;
  }
  client += `    },\n`;
}
client += `  };\n}\n\nexport type Namespaces = ReturnType<typeof buildNamespaces>;\n`;
writeFileSync(join(out, "client.ts"), client);
console.log(`generated ${ops.length} operations in ${byTag.size} namespaces`);
